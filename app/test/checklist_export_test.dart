import 'package:flutter_test/flutter_test.dart';
import 'package:kumpleto/data/checklist_export.dart';
import 'package:kumpleto/l10n/app_localizations_en.dart';
import 'package:kumpleto/models/localized_text.dart';
import 'package:kumpleto/models/models.dart';

/// Share and print must say the same thing: both come from the same outline,
/// and the footer always carries the unofficial notice.
void main() {
  final bundle = Bundle(
    id: 'job-hunt-pack',
    name: const LocalizedText(en: 'Job Hunt Pack', fil: 'Job Hunt Pack'),
    description: const LocalizedText(en: 'Docs for applying', fil: 'Mga dok'),
    status: DocStatus.verified,
    documentIds: const ['nbi-clearance'],
  );

  final document = Document(
    id: 'nbi-clearance',
    name: const LocalizedText(en: 'NBI Clearance', fil: 'NBI Clearance'),
    agencyId: 'nbi',
    status: DocStatus.verified,
    validityMonths: 6,
    sourceUrl: 'https://nbi.gov.ph/',
    requirements: const [
      Requirement(
        id: 'valid-ids',
        text: LocalizedText(en: 'Two valid IDs', fil: 'Dalawang valid ID'),
        original: true,
        photocopies: 2,
      ),
      Requirement(
        id: 'barangay-cert',
        text: LocalizedText(en: 'Barangay certificate', fil: 'Barangay cert'),
        optional: true,
      ),
    ],
    steps: const [
      LocalizedText(en: 'Register online.', fil: 'Mag-register online.'),
    ],
    feeNote: const LocalizedText(en: '₱130 plus charges', fil: '₱130'),
  );

  ChecklistContent content(String languageCode) => ChecklistContent(
    l10n: AppLocalizationsEn(),
    languageCode: languageCode,
    bundle: bundle,
    documents: [document],
    agencyOf: (_) => 'National Bureau of Investigation',
    footer: 'Generated by Kumpleto on 1/2/27.',
  );

  test('text export lists requirements, steps and details', () {
    final text = checklistText(content('en'));

    expect(text, startsWith('JOB HUNT PACK'));
    expect(text, contains('1. NBI Clearance — National Bureau of Investigation'));
    // Original + photocopies are spelled out so the line is actionable.
    expect(text, contains('[ ] Two valid IDs (original, 2 photocopies)'));
    expect(text, contains('[ ] Barangay certificate (optional)'));
    expect(text, contains('1) Register online.'));
    expect(text, contains('Fees: ₱130 plus charges'));
    expect(text, contains('Validity: Valid for 6 months'));
    expect(text, contains('Original: https://nbi.gov.ph/'));
    expect(text, endsWith('Generated by Kumpleto on 1/2/27.'));
  });

  test('text export follows the chosen language', () {
    final text = checklistText(content('fil'));
    expect(text, contains('Dalawang valid ID'));
    expect(text, isNot(contains('Two valid IDs')));
  });

  test('pdf export produces a real PDF without the peso glyph', () async {
    final bytes = await checklistPdf(content('en'));

    expect(bytes.length, greaterThan(1000));
    // Every PDF starts with the %PDF header.
    expect(String.fromCharCodes(bytes.take(4)), '%PDF');
    // Base-14 fonts cannot render ₱, so the fee line is written as PHP.
    final raw = String.fromCharCodes(bytes);
    expect(raw.contains('₱'), isFalse);
  });
}
